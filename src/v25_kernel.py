@dataclass
class SwarmAgentNode:
    agent_id: str
    parent_id: Optional[str]
    depth: int
    max_depth: int
    quota: int
    damping_factor: float
    active_children: List[str] = field(default_factory=list)
    consumed_tokens: int = 0


class RecursiveSubRingRouter:
    """
    Guarantees finite convergence and bounded blast radius across
    recursively spawned multi-agent swarms.
    
    Convergence Law:
    For parent quota Q_0 and damping factor alpha in (0, 1),
    the total swarm capacity is strictly bounded:
        Total_Swarm_Quota <= Q_0 / (1 - alpha) < infinity
    """
    def __init__(self, root_agent_id: str, initial_quota: int = 10000, max_depth: int = 4, damping_factor: float = 0.5):
        self.root_agent_id = root_agent_id
        self.damping_factor = damping_factor
        self.max_depth = max_depth
        self.nodes: Dict[str, SwarmAgentNode] = {
            root_agent_id: SwarmAgentNode(
                agent_id=root_agent_id,
                parent_id=None,
                depth=0,
                max_depth=max_depth,
                quota=initial_quota,
                damping_factor=damping_factor
            )
        }
        self.total_allocated_quota = initial_quota

    def spawn_sub_agent(self, parent_id: str, child_id: str) -> Tuple[bool, Optional[str]]:
        if parent_id not in self.nodes:
            return False, f"PARENT_NOT_FOUND: Parent agent '{parent_id}' does not exist in topology"

        parent = self.nodes[parent_id]

        if parent.depth >= self.max_depth:
            return False, f"RECURSION_DEPTH_EXCEEDED: Sub-agent spawn exceeds maximum depth {self.max_depth}"

        # Calculate geometric damped quota with strict parent budget deduction
        child_quota = int(parent.quota * self.damping_factor)
        if child_quota <= 0:
            return False, f"QUOTA_EXHAUSTION: Damped child quota is 0; spawning halted"
        if parent.quota - child_quota < 0:
            return False, f"PARENT_BUDGET_EXHAUSTED: Parent has insufficient quota to spawn child"

        parent.quota -= child_quota  # Conserve total system energy/tokens

        child_node = SwarmAgentNode(
            agent_id=child_id,
            parent_id=parent_id,
            depth=parent.depth + 1,
            max_depth=self.max_depth,
            quota=child_quota,
            damping_factor=self.damping_factor
        )

        parent.active_children.append(child_id)
        self.nodes[child_id] = child_node

        return True, None

    def consume_quota(self, agent_id: str, units: int) -> Tuple[bool, Optional[str]]:
        if agent_id not in self.nodes:
            return False, f"AGENT_NOT_FOUND: Agent '{agent_id}' not found"

        agent = self.nodes[agent_id]
        if agent.consumed_tokens + units > agent.quota:
            return False, f"QUOTA_BREACH: Agent '{agent_id}' requested {units} but has only {agent.quota - agent.consumed_tokens} remaining"

        agent.consumed_tokens += units
        return True, None

    def get_swarm_metrics(self) -> Dict[str, Any]:
        total_current_quota = sum(n.quota for n in self.nodes.values())
        return {
            "total_agents": len(self.nodes),
            "max_tree_depth": max(n.depth for n in self.nodes.values()),
            "total_system_quota": total_current_quota,
            "root_initial_quota": self.total_allocated_quota,
        }


